// Native component sets: JSX types for their tags, from the manifests a host
// prints with `--manifest`, and the hashes the runtime checks at startup.

const ident = name => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));
const doc = (text, indent) => (text ? `${indent}/** ${text.replace(/\*\//g, "*\\/")} */\n` : "");

function attrType(attr) {
  switch (attr.type) {
    case "enum":
      return attr.values.map(v => JSON.stringify(v)).join(" | ");
    case "boolean":
      return "boolean";
    case "number":
      return "number";
    default:
      return "string";
  }
}

const eventProp = event => `on${event[0].toUpperCase()}${event.slice(1)}`;

/**
 * A `.d.ts` that types each set's tags as JSX intrinsic elements.
 * @param {any[]} manifests
 */
export function componentTypes(manifests) {
  let out = `// Generated by \`chouquette components\` from ${manifests.map(m => `${m.set} (${m.hash})`).join(", ")}. Do not edit.
import type { HostSyntheticEvent } from "../events";

type KitProps = { "aria-label"?: string; id?: string; className?: string; key?: React.Key };

declare module "react" {
  namespace JSX {
    interface IntrinsicElements {
`;
  for (const manifest of manifests) {
    for (const c of manifest.components) {
      out += doc(c.doc, "      ");
      out += `      ${JSON.stringify(c.tag)}: KitProps & {\n`;
      for (const attr of c.attrs) {
        if (attr.name === "class") continue;
        out += doc(attr.doc, "        ");
        out += `        ${ident(attr.name)}${attr.required ? "" : "?"}: ${attrType(attr)};\n`;
      }
      for (const event of c.events ?? []) out += `        ${eventProp(event)}?: (e: HostSyntheticEvent) => void;\n`;
      if (c.children) out += `        children?: React.ReactNode;\n`;
      out += `      };\n`;
    }
  }
  return `${out}    }\n  }\n}\n`;
}

/** Each set's manifest hash, by name: what the runtime sends `check_components`. */
export const hashes = manifests => Object.fromEntries(manifests.map(m => [m.set, m.hash]));
